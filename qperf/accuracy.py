"""Op-specific accuracy statements and the calibrated shape range of each data-movement factory.

The cost profile's platform_scope says what a simulator times; how close the model is depends on the op and factory.
binary_ng: the mean errors of docs/CALIBRATION.md (BINARY). Data-movement ops: profiles/accuracy.json, generated by
calibration/make_accuracy.py from calibration/data (mean error per profile, factory and dtype, and the largest rows,
width and elements among the factory's runs; tests/test_accuracy.py keeps it current). A profile derived from another
(silicon-hypothesis: calibration.derived_from ttsim-perf@...) borrows the source's numbers and says it is a hypothesis.
"""

from __future__ import annotations

import json
import os

from . import profiles

RANGE_TOLERANCE = 1.25  # a shape is extrapolated when rows, width or elements exceed the calibrated maximum by more
# binary_ng bf16 / fp32 mean errors over the calibration runs (docs/CALIBRATION.md, Accuracy)
BINARY = {
    "craq-sim": {"bf16": {"add": "2.1%", "multiply": "1.4%"}, "fp32": {"add": "1.5%", "multiply": "1.5%"}},
    "ttsim-perf": {"bf16": {"dram": ("1.4%",), "l1": ("8.5%", "up to 41% at dm_batch=1")},
                   "fp32": {"dram": ("<= 0.8%",), "l1": ("9%",)}},
}
_table = None


def table():
    """profiles/accuracy.json, or {} when absent (a QPERF_PROFILES tree without it)."""
    global _table
    if _table is None:
        path = os.path.join(profiles.ROOT, "accuracy.json")
        try:
            with open(path) as f:
                _table = json.load(f).get("profiles", {})
        except OSError:
            _table = {}
    return _table


def source_of(profile):
    """(name of the profile whose calibration applies, derived: bool). silicon-hypothesis -> (ttsim-perf, True)."""
    name = profile["name"]
    if name in table() or name in BINARY:
        return name, False
    src = (profile.get("calibration") or {}).get("derived_from", "").partition("@")[0]
    return (src, True) if src else (name, False)


def _pct(x):
    return f"{100 * x:.1f}%"


def assumed_dram(profile):
    p = profile.get("params", {})
    bw, eff = p.get("dram.total_bytes_per_cycle"), p.get("dram.efficiency")
    if not bw:
        return "assumed DRAM bandwidth"
    v = lambda x: x["value"] if isinstance(x, dict) else x  # noqa: E731
    gbs = v(bw) * profile["clock"]["GHz"]
    return (f"assumed DRAM bandwidth {gbs:.0f} GB/s x {v(eff) if eff else 1:g} efficiency "
            f"({v(bw):g} B/cycle at {profile['clock']['GHz']:g} GHz)")


def factory_entry(profile, op, factory):
    src, _ = source_of(profile)
    return table().get(src, {}).get("factories", {}).get(f"{op} {factory}")


def _factory_error(profile, op, factory, dtype):
    """(mean error or None, dtype it was measured on or None, runs) of the factory on the calibration source."""
    e = factory_entry(profile, op, factory)
    if e is None:
        return None, None, 0
    dt = dtype if dtype in e["error"] else next(iter(sorted(e["error"])))  # dtype not measured: the bf16 fit
    return e["error"][dt]["mean"], dt, e["error"][dt]["runs"]


def hypothetical_note(profile, op, factory, dtype):
    """The accuracy of a hypothetical design of the factory (no simulator can run it)."""
    src = source_of(profile)[0]
    err, dt, _ = _factory_error(profile, op, factory, dtype)
    return (f"hypothetical setup: no simulator measurement; built from costs with "
            f"{_pct(err) if err is not None else 'unknown'} error on the factory ({op} {factory}, {src}"
            f"{'' if dt in (None, dtype) else f', {dt} runs'})")


def _derived(profile, what):
    return (f"{profile['name']} is a hypothesis, no measurement: {what}; clock, NoC latency and "
            f"{assumed_dram(profile)} are assumptions")


def layout(profile, op, factory, dtype, hypothetical=False, overrides=False):
    """The accuracy statement of one data-movement row."""
    src, derived = source_of(profile)
    err, dt, runs = _factory_error(profile, op, factory, dtype)
    measured = ("no calibration runs" if err is None else
                ("" if dt == dtype else f"no {dtype} runs; ") + f"{_pct(err)} mean error over {runs} {dt} simulator runs")
    if derived and hypothetical:
        s = _derived(profile, f"hypothetical setup, no simulator measurement either; built from {src} costs with "
                              f"{_pct(err) if err is not None else 'unknown'} error on the factory ({op} {factory})")
    elif derived:
        s = _derived(profile, f"instruction costs from {src}, where {op} {factory} has {measured}")
    elif hypothetical:
        s = hypothetical_note(profile, op, factory, dtype)
    elif err is None:
        s = f"no calibration runs of {op} {factory} on {src}: accuracy unknown"
    else:
        s = f"{op} {factory} on {src}: {measured}"
    if overrides:
        s += "; cost overrides applied: the error is that of the profile's own costs"
    return s


def binary(profile, op, dtype, placements, overrides=False):
    """The accuracy statement of a binary_ng answer (op, dtype, operand placements)."""
    src, derived = source_of(profile)
    nums = BINARY.get(src, {}).get(dtype) or BINARY.get(src, {}).get("bf16")
    if not nums:
        s = f"binary_ng on {src}: no calibration runs, accuracy unknown"
    elif "dram" in nums:  # by placement: ttsim-perf times L1 transfers, not DRAM
        l1 = "l1" in placements
        here, there = (nums["l1"], nums["dram"]) if l1 else (nums["dram"], nums["l1"])
        s = (f"binary_ng {dtype} on {src}: {here[0]} mean error with "
             f"{'an L1-interleaved operand' if l1 else 'DRAM / borrowed operands'}, as here"
             + (f" ({here[1]})" if len(here) > 1 else "") + f"; {there[0]} with "
             + ("DRAM / borrowed operands" if l1 else "L1-interleaved operands"))
    else:
        s = f"binary_ng {op} {dtype} on {src}: {nums.get(op, '?')} mean error over the calibration runs"
    if derived:
        s = _derived(profile, f"instruction costs from {src} ({s})")
    if overrides:
        s += "; cost overrides applied: the error is that of the profile's own costs"
    return s


def calibrated_range(profile, op, factory):
    """{"max_h", "max_w", "max_elems", "runs", "profile"} of the factory's calibration runs, or None."""
    e = factory_entry(profile, op, factory)
    if not e:
        return None
    return {"max_h": e["max_h"], "max_w": e["max_w"], "max_elems": e["max_elems"], "runs": e["runs"],
            "profile": source_of(profile)[0]}


def outside(rng, H, W):
    """True when [H, W] exceeds the calibrated range (rows, width or elements beyond RANGE_TOLERANCE x the max)."""
    t = RANGE_TOLERANCE
    return bool(rng) and (H > t * rng["max_h"] or W > t * rng["max_w"] or H * W > t * rng["max_elems"])


def range_warning(profile, op, factory, H, W, rng=None):
    """The extrapolation warning for one shape, or None inside the range."""
    rng = rng or calibrated_range(profile, op, factory)
    if not outside(rng, H, W):
        return None
    return (f"shape {H}x{W} is outside the calibrated range for {op} {factory} on {range_on(profile, rng)} "
            f"({range_txt(rng)}): extrapolated")


def range_on(profile, rng):
    """The profile the range was measured on, naming the derived profile asking."""
    return rng["profile"] + ("" if rng["profile"] == profile["name"] else f", whose costs {profile['name']} uses")


def range_txt(rng):
    """'max 4096x4096, 8.4M elements, 112 runs': the largest rows and width (not necessarily of one run)."""
    return f"max {rng['max_h']}x{rng['max_w']}, {rng['max_elems'] / 1e6:.1f}M elements, {rng['runs']} runs"
