"""Op-specific accuracy statements and the calibrated shape range of each data-movement factory.

The cost profile's platform_scope says what a simulator times; how close the model is depends on the op and factory.
binary_ng add / multiply: the mean errors of docs/CALIBRATION.md (BINARY); the other binary_ng ops (subtract, divide,
FPU multiply): profiles/accuracy.json binary_ng, per compute variant (mean error over its calibration runs, fit and
holdout, per placement), from calibration/data/binops-<profile>.jsonl. Data-movement ops: profiles/accuracy.json, generated by
calibration/make_accuracy.py from calibration/data (mean error per profile, factory and dtype, and the largest rows,
width and elements among the factory's runs; tests/test_accuracy.py keeps it current). A profile derived from another
(silicon-hypothesis: calibration.derived_from ttsim-perf@...) borrows the source's numbers and says it is a hypothesis.
A hypothetical design knob run on the simulators as a kernel variant (accuracy.json hypothetical_validation, e.g. tilize
Default write_batch, dfb_blocks, split cols) is stated as validated; a row whose knobs are all validated is validated
(with the runs of that combination where they exist), partly validated when some knob has no runs.
"""

from __future__ import annotations

import json
import os

from . import profiles

RANGE_TOLERANCE = 1.25  # a shape is extrapolated when rows, width or elements exceed the calibrated maximum by more
# binary_ng bf16 / fp32 mean errors over the calibration runs (docs/CALIBRATION.md, Accuracy)
BINARY = {
    "craq-sim": {"bf16": {"add": "2.1%", "multiply": "1.4%"}, "fp32": {"add": "1.5%", "multiply": "1.5%"}},
    "ttsim-perf": {"bf16": {"dram": ("1.4%",), "l1": ("8.5%", "up to 41% at dm_batch=1")},
                   "fp32": {"dram": ("<= 0.8%",), "l1": ("9%",)}},
}
_table = None
_validation = None
_binary = None


def _load():
    global _table, _validation, _binary
    if _table is None:
        path = os.path.join(profiles.ROOT, "accuracy.json")
        try:
            with open(path) as f:
                raw = json.load(f)
        except OSError:
            raw = {}
        _table, _validation = raw.get("profiles", {}), raw.get("hypothetical_validation", {})
        _binary = raw.get("binary_ng", {})


def table():
    """profiles/accuracy.json, or {} when absent (a QPERF_PROFILES tree without it)."""
    _load()
    return _table


def binary_table():
    """profiles/accuracy.json binary_ng: {profile: {variant: {"runs", "mean", "max", "fit", "holdout",
    "by_placement", "same_as"?}}}, or {}."""
    _load()
    return _binary


CATEGORICAL = ("split",)  # knobs validated per value (split cols says nothing about split 2d)
KNOB_DEFAULT = {"split": "rows"}  # the pinned kernels' value (numeric knobs: 1)


def validation(profile, op, factory, knob, value=None):
    """The simulator validation of one hypothetical design knob of a factory on the profile's calibration source
    ({"mean", "max", "runs", "speedup_mean", "values", "data"}), or None. knob "a+b": runs that changed both together.
    A categorical knob (split) is validated only for the values that ran."""
    _load()
    v = _validation.get(f"{op} {factory} {knob}", {}).get(source_of(profile)[0])
    if v and value is not None and knob in CATEGORICAL and value not in v["values"]:
        return None
    return v


def validated_knobs(design, changed):
    """{knob: value} of the design knobs a hypothetical setup changes (resolve_design's `changed`), as the accuracy
    statement checks them: the core count a split itself sets (cores left at the default) belongs to the split."""
    from .ops.layout import GRID

    design = {k: v for k, v in (design or {}).items() if v is not None}
    names = {ch.split("=")[0] for ch in changed}
    if "split" in names and design.get("cores", GRID) == GRID:
        names.discard("cores")
    return {k: design.get(k) for k in sorted(names)}


def validation_txt(profile, knob, v):
    """'write_batch validated: the factory's own kernels with only write_batch changed (4, 8) ran 24 times on
    ttsim-perf over 12 shapes (H 32-4096, W 256-2048): 0.8% mean error, 1.0% on the speedup over write_batch=1'.
    knob "a+b": the runs that changed both knobs together, against the pinned kernels."""
    both = knob.split("+")
    base = "the pinned kernels" if len(both) > 1 else f"{knob}={KNOB_DEFAULT.get(knob, 1)}"
    sp = "" if v.get("speedup_mean") is None else f", {_pct(v['speedup_mean'])} on the speedup over {base}"
    what = f"{knob} validated" if len(both) == 1 else f"{' and '.join(both)} validated together"
    return (f"{what}: the factory's own kernels with only {' and '.join(both)} changed "
            f"({('; ' if len(both) > 1 else ', ').join(map(str, v['values']))}) ran {v['runs']} times on {source_of(profile)[0]}{_shape_range(v)}: "
            f"{_pct(v['mean'])} mean error{sp}")


def _shape_range(v):
    """' over 12 shapes (H 32-4096, W 256-2048)' from the validation dataset, or ''."""
    import json
    import os
    try:
        path = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), v["data"])
        hw = {(r["H"], r["W"]) for r in map(json.loads, open(path))}
    except (KeyError, OSError, ValueError):
        return ""
    hs, ws = sorted({h for h, _ in hw}), sorted({w for _, w in hw})
    return f" over {len(hw)} shapes (H {hs[0]}-{hs[-1]}, W {ws[0]}-{ws[-1]})"


def source_of(profile):
    """(name of the profile whose calibration applies, derived: bool). silicon-hypothesis -> (ttsim-perf, True)."""
    name = profile["name"]
    if name in table() or name in BINARY or name in binary_table():
        return name, False
    src = (profile.get("calibration") or {}).get("derived_from", "").partition("@")[0]
    return (src, True) if src else (name, False)


def _pct(x):
    return f"{100 * x:.1f}%"


def channel_model(profile):
    """True when the profile times DRAM with the channel model (qperf/dram.py)."""
    m = profile.get("params", {}).get("dram.model")
    return (m.get("value") if isinstance(m, dict) else m) == "channels"


def channel_note(profile):
    """The DRAM statement of a channel-model profile's answers."""
    n = profile["params"]["dram.channels"]
    n = n["value"] if isinstance(n, dict) else n
    return (f"DRAM: channel model ({n} channels, assumed rate/latency; structure from ttsim-perf's Blackhole DRAM model; "
            f"not calibrated on Quasar)")


def assumed_dram(profile):
    p = profile.get("params", {})
    bw, eff = p.get("dram.total_bytes_per_cycle"), p.get("dram.efficiency")
    v = lambda x: x["value"] if isinstance(x, dict) else x  # noqa: E731
    if channel_model(profile):
        n, rate, idle = v(p["dram.channels"]), v(p["dram.channel_bytes_per_cycle"]), v(p.get("dram.idle_latency", 0))
        ghz = profile["clock"]["GHz"]
        return (f"assumed DRAM channels ({n:g} x {rate:g} B/cycle = {n * rate * ghz:.0f} GB/s at {ghz:g} GHz, "
                f"{idle:g}-cycle idle-read latency)")
    if not bw:
        return "assumed DRAM bandwidth"
    gbs = v(bw) * profile["clock"]["GHz"]
    return (f"assumed DRAM bandwidth {gbs:.0f} GB/s x {v(eff) if eff else 1:g} efficiency "
            f"({v(bw):g} B/cycle at {profile['clock']['GHz']:g} GHz)")


def factory_entry(profile, op, factory):
    src, _ = source_of(profile)
    return table().get(src, {}).get("factories", {}).get(f"{op} {factory}")


def _factory_error(profile, op, factory, dtype):
    """(mean error or None, dtype it was measured on or None, runs) of the factory on the calibration source."""
    e = factory_entry(profile, op, factory)
    if e is None:
        return None, None, 0
    dt = dtype if dtype in e["error"] else next(iter(sorted(e["error"])))  # dtype not measured: the bf16 fit
    return e["error"][dt]["mean"], dt, e["error"][dt]["runs"]


def hypothetical_note(profile, op, factory, dtype, knobs=None):
    """The accuracy of a hypothetical design of the factory. knobs: the design knobs it changes ({knob: value}, see
    validated_knobs, or names); those with simulator runs of a kernel variant (validation) are stated as validated,
    the others have no simulator measurement. All validated: also the runs of that combination, where they exist."""
    src = source_of(profile)[0]
    err, dt, _ = _factory_error(profile, op, factory, dtype)
    base = (f"built from costs with {_pct(err) if err is not None else 'unknown'} error on the factory ({op} {factory}, "
            f"{src}{'' if dt in (None, dtype) else f', {dt} runs'})")
    knobs = dict(knobs) if isinstance(knobs, dict) else dict.fromkeys(knobs or ())
    checked = {k: validation(profile, op, factory, k, knobs[k]) for k in sorted(knobs)}
    done = [validation_txt(profile, k, v) for k, v in checked.items() if v]
    rest = [k for k, v in checked.items() if not v]
    combo = "+".join(sorted(knobs))
    together = validation(profile, op, factory, combo) if len(knobs) > 1 and not rest else None
    if together:
        done.append(validation_txt(profile, combo, together))
    if done and not rest:
        return f"hypothetical setup: {'; '.join(done)}; {base}"
    if done:
        return (f"hypothetical setup, partly validated: {'; '.join(done)}; {', '.join(rest)}: no simulator measurement; "
                f"{base}")
    return f"hypothetical setup: no simulator measurement; {base}"


def _derived(profile, what):
    s = (f"{profile['name']} is a hypothesis, no measurement: {what}; clock, NoC latency and "
         f"{assumed_dram(profile)} are assumptions")
    return s + (f"; {channel_note(profile)}" if channel_model(profile) else "")


def layout(profile, op, factory, dtype, hypothetical=False, overrides=False, knobs=None):
    """The accuracy statement of one data-movement row (knobs: the design knobs a hypothetical row changes)."""
    src, derived = source_of(profile)
    err, dt, runs = _factory_error(profile, op, factory, dtype)
    measured = ("no calibration runs" if err is None else
                ("" if dt == dtype else f"no {dtype} runs; ") + f"{_pct(err)} mean error over {runs} {dt} simulator runs")
    if derived and hypothetical:
        s = _derived(profile, f"hypothetical setup, no simulator measurement either; built from {src} costs with "
                              f"{_pct(err) if err is not None else 'unknown'} error on the factory ({op} {factory})")
    elif derived:
        s = _derived(profile, f"instruction costs from {src}, where {op} {factory} has {measured}")
    elif hypothetical:
        s = hypothetical_note(profile, op, factory, dtype, knobs)
    elif err is None:
        s = f"no calibration runs of {op} {factory} on {src}: accuracy unknown"
    else:
        s = f"{op} {factory} on {src}: {measured}"
    if overrides:
        s += "; cost overrides applied: the error is that of the profile's own costs"
    return s


def _variant_statement(src, variant, e, placements):
    """'binary_ng divide bf16 (SFPU) on craq-sim: 0.8% mean error over 66 simulator runs (fit 0.7%, holdout 1.2%)',
    by placement on ttsim-perf (it times L1 transfers), and naming the variant it runs as cycle for cycle."""
    kind, op, dtype = variant.split(":")
    name = f"binary_ng {op} {dtype} ({kind.upper()}{', fast_and_approximate_mode' if kind == 'fpu' and op == 'multiply' else ''})"
    same = f"; runs cycle for cycle as {e['same_as'].split(':')[1]} (same costs)" if e.get("same_as") else ""
    bp = e.get("by_placement", {})
    if src == "ttsim-perf" and "l1" in bp:
        l1 = "l1" in placements
        here = bp["l1"] if l1 else e.get("dram_borrowed", {})
        there = e.get("dram_borrowed", {}) if l1 else bp["l1"]
        return (f"{name} on {src}: {_pct(here['mean'])} mean error over {here['runs']} simulator runs with "
                f"{'an L1-interleaved operand' if l1 else 'DRAM / borrowed operands'}, as here; "
                f"{_pct(there['mean'])} with {'DRAM / borrowed operands' if l1 else 'L1-interleaved operands'}"
                f" (ttsim-perf's L1 transfer gap, as add){same}")
    return (f"{name} on {src}: {_pct(e['mean'])} mean error over {e['runs']} simulator runs (fit {_pct(e['fit'])}, "
            f"holdout {_pct(e['holdout'])}){same}")


def binary(profile, op, dtype, placements, overrides=False, variant=None):
    """The accuracy statement of a binary_ng answer (op, dtype, operand placements; variant: the compute variant,
    e.g. fpu:multiply:bf16, whose table entry is used for the ops beyond add / multiply on their default kernel)."""
    src, derived = source_of(profile)
    nums = BINARY.get(src, {}).get(dtype) or BINARY.get(src, {}).get("bf16")
    e = binary_table().get(src, {}).get(variant) if variant else None
    if e:
        s = _variant_statement(src, variant, e, placements)
    elif op not in ("add", "multiply") or (variant and variant.startswith("fpu:multiply")):
        s = f"binary_ng {variant or op} on {src}: no calibration runs, accuracy unknown"
    elif not nums:
        s = f"binary_ng on {src}: no calibration runs, accuracy unknown"
    elif "dram" in nums:  # by placement: ttsim-perf times L1 transfers, not DRAM
        l1 = "l1" in placements
        here, there = (nums["l1"], nums["dram"]) if l1 else (nums["dram"], nums["l1"])
        s = (f"binary_ng {dtype} on {src}: {here[0]} mean error with "
             f"{'an L1-interleaved operand' if l1 else 'DRAM / borrowed operands'}, as here"
             + (f" ({here[1]})" if len(here) > 1 else "") + f"; {there[0]} with "
             + ("DRAM / borrowed operands" if l1 else "L1-interleaved operands"))
    else:
        s = f"binary_ng {op} {dtype} on {src}: {nums.get(op, '?')} mean error over the calibration runs"
    if derived:
        s = _derived(profile, f"instruction costs from {src} ({s})")
    if overrides:
        s += "; cost overrides applied: the error is that of the profile's own costs"
    return s


def calibrated_range(profile, op, factory):
    """{"max_h", "max_w", "max_elems", "runs", "profile"} of the factory's calibration runs, or None."""
    e = factory_entry(profile, op, factory)
    if not e:
        return None
    return {"max_h": e["max_h"], "max_w": e["max_w"], "max_elems": e["max_elems"], "runs": e["runs"],
            "profile": source_of(profile)[0]}


def outside(rng, H, W):
    """True when [H, W] exceeds the calibrated range (rows, width or elements beyond RANGE_TOLERANCE x the max)."""
    t = RANGE_TOLERANCE
    return bool(rng) and (H > t * rng["max_h"] or W > t * rng["max_w"] or H * W > t * rng["max_elems"])


def range_warning(profile, op, factory, H, W, rng=None):
    """The extrapolation warning for one shape, or None inside the range."""
    rng = rng or calibrated_range(profile, op, factory)
    if not outside(rng, H, W):
        return None
    return (f"shape {H}x{W} is outside the calibrated range for {op} {factory} on {range_on(profile, rng)} "
            f"({range_txt(rng)}): extrapolated")


def range_on(profile, rng):
    """The profile the range was measured on, naming the derived profile asking."""
    return rng["profile"] + ("" if rng["profile"] == profile["name"] else f", whose costs {profile['name']} uses")


def range_txt(rng):
    """'max 4096x4096, 8.4M elements, 112 runs': the largest rows and width (not necessarily of one run)."""
    return f"max {rng['max_h']}x{rng['max_w']}, {rng['max_elems'] / 1e6:.1f}M elements, {rng['runs']} runs"
